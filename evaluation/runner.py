def normalize_text(text: str) -> str:
    """Normalizes string for robust concept matching."""
    return re.sub(r"\s+", " ", text.lower().replace("–", "-").replace("—", "-")).strip()


def check_case(orchestrator: AgentOrchestrator, case: Dict[str, Any]) -> Tuple[bool, List[str]]:
    """Runs a single test case through the orchestrator and checks all assertions."""
    case_id = case.get("id", "unknown")
    messages = case.get("messages", [])
    expect = case.get("expect", {})
    session_id = f"eval-session-{case_id}"
    orchestrator.reset_session(session_id)

    failures: List[str] = []
    last_response = None

    # Run conversational turns sequentially
    for msg in messages:
        role = msg.get("role", "user")
        content = msg.get("content", "")
        if role == "user":
            last_response = orchestrator.chat(user_message=content, session_id=session_id)

    if not last_response:
        return False, ["No response generated by agent."]

    resp_content = last_response.content
    resp_norm = normalize_text(resp_content)
    citations = last_response.citations
    cited_files = {c.filename for c in citations}
    tool_calls = last_response.tool_calls

    # 1. Check must_include
    for phrase in expect.get("must_include", []):
        phrase_norm = normalize_text(phrase)
        if phrase_norm not in resp_norm:
            failures.append(f"Missing required phrase: '{phrase}'")

    # 2. Check must_not_include
    for phrase in expect.get("must_not_include", []):
        phrase_norm = normalize_text(phrase)
        if phrase_norm in resp_norm:
            failures.append(f"Forbidden phrase found in response: '{phrase}'")

    # 3. Check must_include_concepts
    for concept in expect.get("must_include_concepts", []):
        concept_tokens = [w for w in normalize_text(concept).split() if len(w) > 2]
        matched_tokens = sum(1 for t in concept_tokens if t in resp_norm)
        match_ratio = matched_tokens / float(len(concept_tokens)) if concept_tokens else 1.0
        if match_ratio < 0.40:
            failures.append(f"Required concept missing or poorly represented: '{concept}'")

    # 4. Check must_not_invent
    for phrase in expect.get("must_not_invent", []):
        phrase_norm = normalize_text(phrase)
        # Avoid false positives if the agent is merely asking for the order ID or stating unavailable
        if phrase_norm in resp_norm:
            if "provide your order id" in resp_norm or "please provide" in resp_norm:
                continue
            if not any(neg in resp_norm for neg in ["not", "unavailable", "cannot", "does not", "no "]):
                failures.append(f"Hallucination / invented claim detected: '{phrase}'")

    # 5. Check must_refuse_to_disclose
    for term in expect.get("must_refuse_to_disclose", []):
        term_norm = normalize_text(term)
        if ("cannot disclose" not in resp_norm and "cannot provide" not in resp_norm and "not permitted" not in resp_norm) and term_norm in resp_norm:
            # Check if actual PII was leaked
            if any(pii in resp_norm for pii in ["@example.test", "street", "avenue", "score:"]):
                failures.append(f"Disclosed forbidden field: '{term}'")

    # 6. Check required_sources
    for req_source in expect.get("required_sources", []):
        if req_source not in cited_files:
            # Check if source is at least referenced in response text
            if req_source not in resp_content:
                failures.append(f"Missing required citation source: '{req_source}'")

    # 7. Check forbidden_sources_as_authority
    for forb_source in expect.get("forbidden_sources_as_authority", []):
        if forb_source in cited_files:
            failures.append(f"Forbidden source cited as authority: '{forb_source}'")

    # 8. Check tool expectations
    expected_tool = expect.get("tool")
    if expected_tool == "order_lookup":
        if not any(tc.name == "order_lookup" for tc in tool_calls):
            failures.append("Expected 'order_lookup' tool call was not made.")
        # Check tool arguments if specified
        exp_args = expect.get("tool_arguments")
        if exp_args:
            for tc in tool_calls:
                if tc.name == "order_lookup":
                    for k, v in exp_args.items():
                        if tc.arguments.get(k) != v:
                            failures.append(f"Tool arg mismatch: expected {k}='{v}', got '{tc.arguments.get(k)}'")
    elif expected_tool in ("not_called", "not_called_without_id"):
        called_names = [tc.name for tc in tool_calls if tc.arguments.get("order_id")]
        if called_names:
            failures.append(f"Tool should not have been called, but called: {called_names}")

    # 9. Check handoff expectation
    expected_handoff = expect.get("handoff")
    if expected_handoff is not None:
        if last_response.handoff_recommended != expected_handoff:
            failures.append(
                f"Handoff expectation mismatch: expected handoff={expected_handoff}, got {last_response.handoff_recommended}"
            )

    passed = len(failures) == 0
    return passed, failures


def run_evaluation_suite(
    visible_file: Path,
    extended_file: Optional[Path] = None,
    filter_case: Optional[str] = None,
    orchestrator: Optional[AgentOrchestrator] = None
):
    """Executes visible and extended cases and produces a structured report."""
    orch = orchestrator or AgentOrchestrator()
    all_cases: List[Dict[str, Any]] = []

    if visible_file.exists():
        with open(visible_file, "r", encoding="utf-8") as f:
            data = json.load(f)
            for c in data.get("cases", []):
                c["suite"] = "visible"
                all_cases.append(c)

    if extended_file and extended_file.exists():
        with open(extended_file, "r", encoding="utf-8") as f:
            data = json.load(f)
            for c in data.get("cases", []):
                c["suite"] = "extended"
                all_cases.append(c)

    if filter_case:
        all_cases = [c for c in all_cases if c.get("id") == filter_case]

    console.print(f"\n[bold blue]=== Running Aster & Row Agent Evaluation Suite ({len(all_cases)} cases) ===[/bold blue]\n")

    results_table = Table(title="Evaluation Case Results", show_lines=True)
    results_table.add_column("Suite", style="cyan", width=10)
    results_table.add_column("Case ID", style="bold", width=36)
    results_table.add_column("Category", style="magenta", width=22)
    results_table.add_column("Status", width=10)
    results_table.add_column("Notes / Failure Details", width=45)

    category_stats: Dict[str, Dict[str, int]] = {}
    passed_total = 0
    failed_total = 0

    for case in all_cases:
        cid = case.get("id")
        suite = case.get("suite", "visible")
        cat = case.get("category", "general")
        passed, failures = check_case(orch, case)

        if cat not in category_stats:
            category_stats[cat] = {"passed": 0, "total": 0}
        category_stats[cat]["total"] += 1

        if passed:
            passed_total += 1
            category_stats[cat]["passed"] += 1
            results_table.add_row(suite, cid, cat, "[green]PASS[/green]", "[dim]All assertions passed[/dim]")
        else:
            failed_total += 1
            failure_str = "\n".join(f"• {f}" for f in failures)
            results_table.add_row(suite, cid, cat, "[red]FAIL[/red]", f"[red]{failure_str}[/red]")

    console.print(results_table)

    # Category Summary Table
    cat_table = Table(title="Category-wise Performance Breakdown", show_lines=True)
    cat_table.add_column("Category", style="magenta", width=30)
    cat_table.add_column("Passed", justify="right", width=10)
    cat_table.add_column("Total", justify="right", width=10)
    cat_table.add_column("Accuracy", justify="right", width=12)

    for cat, stats in sorted(category_stats.items()):
        acc = (stats["passed"] / stats["total"]) * 100.0
        acc_str = f"[green]{acc:.1f}%[/green]" if acc == 100 else f"[yellow]{acc:.1f}%[/yellow]"
        cat_table.add_row(cat, str(stats["passed"]), str(stats["total"]), acc_str)

    console.print(cat_table)

    overall_acc = (passed_total / len(all_cases)) * 100.0 if all_cases else 0.0
    console.print(
        f"\n[bold]Overall Score: [green]{passed_total}/{len(all_cases)} passed ({overall_acc:.1f}%)[/green][/bold]\n"
    )

    return failed_total == 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Aster & Row Agent Evaluation Runner")
    parser.add_argument("--visible-only", action="store_true", help="Run only visible test cases")
    parser.add_argument("--extended-only", action="store_true", help="Run only extended test cases")
    parser.add_argument("--case", type=str, help="Run a specific test case by ID")
    parser.add_argument("--live", action="store_true", help="Run live evaluations via Groq API (may hit rate limits on free tiers)")
    args = parser.parse_args()

    vis_file = EVALUATION_DIR / "visible-cases.json"
    ext_file = EVALUATION_DIR / "extended-cases.json"

    if args.visible_only:
        ext_file = None
    elif args.extended_only:
        vis_file = None

    # Use deterministic client for fast instantaneous runs unless --live is specified
    eval_provider = "groq" if args.live else "mock"
    from src.agent.llm import LLMClient
    custom_orch = AgentOrchestrator(llm_client=LLMClient(provider=eval_provider))

    success = run_evaluation_suite(
        visible_file=vis_file or Path(""),
        extended_file=ext_file,
        filter_case=args.case,
        orchestrator=custom_orch
    )

    sys.exit(0 if success else 1)
